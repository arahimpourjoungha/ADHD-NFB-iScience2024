%RUN_SUPPLEMENT_S4  Run all Supplementary Section 4 scripts, headless.
%
%   run('examples/run_supplement_s4.m')
%
%   Runs the twelve scripts in analysis/ in order, each in a fresh
%   workspace, saving figures to output/<script name>/ under the repository
%   root (one folder per script, because several scripts write the same
%   file names; known issue B9). Works in matlab -batch; figures are
%   invisible.
%
%   Inputs: if T and demographics already exist in the workspace (for
%   example after load('T.mat') and load('demographics.mat')) they are
%   used; otherwise synthetic tables with planted effects are generated by
%   make_synthetic_inputs. ARStats, if present, is passed to
%   HboGenerateTableAveTwo; otherwise a mock ARStats from tests/ is used.
%   Set outDirRoot beforehand to write somewhere else.
%
%   The saved demographics table names its ID column 'subject' while four
%   scripts expect 'SubjectID' (known issue B4), so the column is renamed
%   here before the scripts run.
%
%   A script that errors is reported and the run continues; a summary
%   table is printed at the end and left in the workspace as s4Summary.

s4Root = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(s4Root, 'analysis'), fullfile(s4Root, 'examples'));
if ~exist('outDirRoot', 'var')
    outDirRoot = fullfile(s4Root, 'output');
end

s4Inputs = struct();
if exist('T', 'var') && exist('demographics', 'var')
    disp('Using T and demographics from the workspace.');
    s4Inputs = struct('T', T, 'demographics', demographics);
else
    disp('No T/demographics in the workspace: generating synthetic inputs (fake subjects).');
    [s4Inputs.T, s4Inputs.demographics] = make_synthetic_inputs();
end
if exist('ARStats', 'var')
    s4Inputs.ARStats = ARStats;
elseif isfile(fullfile(s4Root, 'tests', 'make_mock_ARStats.m'))
    addpath(fullfile(s4Root, 'tests'));
    s4Inputs.ARStats = make_mock_ARStats(s4Inputs.T);
    disp('No ARStats in the workspace: using the mock ChannelStats array from tests/.');
end

% Known issue B4: scripts expect SubjectID
s4Names = s4Inputs.demographics.Properties.VariableNames;
if ismember('subject', s4Names) && ~ismember('SubjectID', s4Names)
    s4Inputs.demographics = renamevars(s4Inputs.demographics, 'subject', 'SubjectID');
end

% Order and settings. The T used downstream is always the one-row-per-
% subject input table, never the per-scan output of HboGenerateTableAveTwo
% (known issue B3).
s4Plan = {
    'HboGenerateTableAveTwo',  struct(),                               'T per GLM entry (step before S8-S10)'
    'HboNFBPlotAveTwo',        struct(),                               'Fig S8'
    'HboWLPlotAveTwo',         struct(),                               'WL counterpart of Fig S8'
    'AccPlotInterventions',    struct(),                               'NFB accuracy, 12 sessions'
    'HboPlotAveTwo',           struct(),                               'NFB accuracy, first vs last two'
    'InterventionCorr',        struct('column_name', 'backAcc2'),      'Fig S9 left'
    'InterventionCorr2',       struct(),                               'Fig S9 right (attempt)'
    'CorrAccDiffAssess',       struct(),                               'Fig S9 (attempt)'
    'hboAllAccnback',          struct(),                               'Fig S10 (attempt)'
    'CorrHboDiffAccNbackDiff', struct(),                               'Fig S10 (attempt)'
    'hboAccnbackDiff',         struct(),                               'Fig S10 (attempt)'
    'hboAssess',               struct(),                               'Fig S10 (attempt)'
    };

s4Status = cell(size(s4Plan, 1), 1);
for s4k = 1:size(s4Plan, 1)
    s4Name = s4Plan{s4k, 1};
    fprintf('\n===== %s (%s) =====\n', s4Name, s4Plan{s4k, 3});
    if strcmp(s4Name, 'HboGenerateTableAveTwo') && ~isfield(s4Inputs, 'ARStats')
        s4Status{s4k} = 'skipped: no ARStats';
        disp(s4Status{s4k});
        continue
    end
    try
        s4Result = run_s4_script(s4Name, fullfile(outDirRoot, s4Name), s4Inputs, s4Plan{s4k, 2});
        % Echo the lines that carry results, not the diagnostic table dumps
        s4Lines = splitlines(s4Result.log);
        s4Keep = contains(s4Lines, {'p-value', 'Correlation coefficient', 'P-value', ': r = ', 'Number of participants'});
        fprintf('%s\n', s4Lines{s4Keep});
        s4Status{s4k} = 'ok';
    catch s4Err
        s4Status{s4k} = ['error: ' s4Err.message];
        fprintf('ERROR (%s): %s\n', s4Err.identifier, s4Err.message);
    end
end

s4Summary = table(s4Plan(:, 1), s4Plan(:, 3), s4Status, 'VariableNames', {'Script', 'Supports', 'Status'});
fprintf('\nFigures written under %s\n\n', outDirRoot);
disp(s4Summary);
